static uint8_t cursor_col, cursor_page;

static void ssd1306_cmd(uint8_t cmd)
{
    uint8_t buf[2] = {0x00, cmd};
    HAL_I2C_Master_Transmit(oled_hi2c, OLED_I2C_ADDR, buf, 2, 10);
}

void OLED_Init(I2C_HandleTypeDef *hi2c)
{
    oled_hi2c = hi2c;
    HAL_Delay(100);

    ssd1306_cmd(0xAE);
    ssd1306_cmd(0xD5); ssd1306_cmd(0x80);
    ssd1306_cmd(0xA8); ssd1306_cmd(0x3F);
    ssd1306_cmd(0xD3); ssd1306_cmd(0x00);
    ssd1306_cmd(0x40);
    ssd1306_cmd(0x8D); ssd1306_cmd(0x14);
    ssd1306_cmd(0x20); ssd1306_cmd(0x00);
    ssd1306_cmd(0xA1);
    ssd1306_cmd(0xC8);
    ssd1306_cmd(0xDA); ssd1306_cmd(0x12);
    ssd1306_cmd(0x81); ssd1306_cmd(0xCF);
    ssd1306_cmd(0xD9); ssd1306_cmd(0xF1);
    ssd1306_cmd(0xDB); ssd1306_cmd(0x40);
    ssd1306_cmd(0xA4);
    ssd1306_cmd(0xA6);
    ssd1306_cmd(0xAF);

    OLED_Clear();
}

void OLED_Clear(void)
{
    uint8_t buf[129];
    buf[0] = 0x40;
    memset(&buf[1], 0x00, 128);

    ssd1306_cmd(0x21); ssd1306_cmd(0); ssd1306_cmd(127);
    ssd1306_cmd(0x22); ssd1306_cmd(0); ssd1306_cmd(7);

    for (int page = 0; page < 8; page++)
        HAL_I2C_Master_Transmit(oled_hi2c, OLED_I2C_ADDR, buf, 129, 50);

    cursor_col  = 0;
    cursor_page = 0;
}

void OLED_SetCursor(uint8_t col, uint8_t row)
{
    cursor_col  = col;
    cursor_page = row;
    ssd1306_cmd(0x21); ssd1306_cmd(col);  ssd1306_cmd(127);
    ssd1306_cmd(0x22); ssd1306_cmd(row);  ssd1306_cmd(7);
}

void OLED_WriteString(const char *str)
{
    uint8_t buf[7];
    buf[0] = 0x40;

    while (*str) {
        uint8_t c = (uint8_t)*str;
        if (c < 32 || c > 126) c = 32;
        const uint8_t *glyph = font5x7[c - 32];

        buf[1] = glyph[0];
        buf[2] = glyph[1];
        buf[3] = glyph[2];
        buf[4] = glyph[3];
        buf[5] = glyph[4];
        buf[6] = 0x00;

        HAL_I2C_Master_Transmit(oled_hi2c, OLED_I2C_ADDR, buf, 7, 10);
        cursor_col += 6;
        str++;
    }
}

